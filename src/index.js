async function processAndForward(rawBody, env) {
  let payload;
  try {
    payload = JSON.parse(rawBody);
  } catch (e) {
    return;
  }
  const makeWebhookUrl = env.MAKE_WEBHOOK_URL;
  const canCapture = !!(env.WHATSAPP_TOKEN && env.SUPABASE_SERVICE_KEY);
  const supabaseUrl = env.SUPABASE_URL || "https://rvigugiufrjmzedjstuz.supabase.co";
  const graph = "https://graph.facebook.com/" + (env.GRAPH_VERSION || "v21.0");
  const MEDIA_TYPES = ["image", "audio", "video", "document", "sticker"];

  // PUNTO 47 — instradamento dei media verso lo scenario "Foto e DDT" (fail-safe).
  // MAKE_WEBHOOK_URL_MEDIA assente  -> tutto al monolite, come prima.
  // MEDIA_SOLO_DA (numeri separati da virgola, facoltativo) -> accensione graduale:
  //   solo i media di quei mittenti vanno al nuovo scenario, gli altri restano al monolite.
  // Per tornare indietro basta rimuovere MAKE_WEBHOOK_URL_MEDIA: nessun deploy necessario.
  const mediaWebhookUrl = env.MAKE_WEBHOOK_URL_MEDIA || "";
  const ROUTE_MEDIA_TYPES = ["image", "document"];
  const soloDa = String(env.MEDIA_SOLO_DA || "").split(",").map((s) => s.replace(/[^0-9]/g, "")).filter(Boolean);

  const entries = payload.entry || [];
  for (const entry of entries) {
    const changes = entry.changes || [];
    for (const change of changes) {
      const value = change.value || {};
      if (!value.messages || value.messages.length === 0) continue;

      // Cattura media (best-effort): non deve MAI impedire l'inoltro a Make.
      if (canCapture) {
        for (const msg of value.messages) {
          const tipo = msg.type;
          if (MEDIA_TYPES.indexOf(tipo) === -1) continue;
          const media = msg[tipo];
          if (!media || !media.id) continue;
          try {
            const captured = await captureMedia(media.id, tipo, msg, env, supabaseUrl, graph);
            if (captured && captured.signed_url) {
              // arricchisce il messaggio SENZA rimuovere nulla (monolite compatibile)
              media.link = captured.signed_url;
              media.storage_path = captured.storage_path;
              msg._media = captured;
            }
          } catch (e) {
            try {
              await logMedia(env, supabaseUrl, {
                message_id: msg.id, telefono: msg.from, tipo,
                mime: (media && media.mime_type) || null,
                storage_path: null, signed_url: null, signed_url_scade: null,
                dimensione_bytes: null, esito: "errore",
                errore: String((e && e.message) || e).slice(0, 500)
              });
            } catch (_) {}
          }
        }
      } else if (env.SUPABASE_SERVICE_KEY) {
        // 04/10/2026: senza WHATSAPP_TOKEN la cattura e' spenta. Lo si scrive nel registro
        // (esito 'errore'), cosi' il problema si vede subito invece di restare silenzioso.
        for (const msg of value.messages) {
          if (MEDIA_TYPES.indexOf(msg.type) === -1) continue;
          const media = msg[msg.type];
          try {
            await logMedia(env, supabaseUrl, {
              message_id: msg.id, telefono: msg.from, tipo: msg.type,
              mime: (media && media.mime_type) || null,
              storage_path: null, signed_url: null, signed_url_scade: null,
              dimensione_bytes: null, esito: "errore",
              errore: "WHATSAPP_TOKEN mancante sul relay: cattura non eseguita"
            });
          } catch (_) {}
        }
      }

      // CHAT UNICA: numeri ammessi (prova + produzione) letti dal database e tenuti in memoria 60 s.
      // Se il database non risponde la lista e' vuota: tutto va a Make come prima.
      let cu = { numeri: [], url: "", chiave: "" };
      try { cu = await chatUnicaConfig(env, supabaseUrl); } catch (e) {}

      // Inoltro a Make di un pacchetto (quello originale o uno costruito dalla chat unica):
      // foto e documenti allo scenario «Foto e DDT», tutto il resto al monolite. Stessa regola di sempre.
      const inoltraAMake = async (bundle) => {
        const m = bundle && Array.isArray(bundle.messages) ? bundle.messages[0] : null;
        if (!m) return false;
        const alMedia = !!mediaWebhookUrl
          && ROUTE_MEDIA_TYPES.indexOf(m.type) !== -1
          && (soloDa.length === 0 || soloDa.indexOf(String(m.from || "")) !== -1);
        const url = alMedia ? mediaWebhookUrl : makeWebhookUrl;
        if (!url) return false;
        try {
          await fetch(url, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(bundle)
          });
          return true;
        } catch (e) { return false; }
      };

      // Un invio per OGNI messaggio, in ordine: gli scenari leggono solo messages[1],
      // quindi se Meta raggruppa più messaggi in una notifica nessuno va perso.
      for (const msg of value.messages) {
        const bundle = {
          id: entry.id,
          time: msg.timestamp ? Number(msg.timestamp) : Math.floor(Date.now() / 1e3),
          field: change.field,
          metadata: value.metadata || {},
          messages: [msg],
          contacts: value.contacts || []
        };
        // TIMBRATURE (04/10/2026): «ENTRO» / «ESCO» come messaggio intero (anche «ENTRO #codice» dal QR
        // in baracca) e' una timbratura di presenza: la registra il database (timbratura_whatsapp), la
        // risposta parte da qui e il pacchetto NON va a Make. Vale per tutti i numeri registrati.
        // FAIL-SAFE: parola non riconosciuta, numero sconosciuto, interruttore spento, database o Meta
        // che non rispondono → il messaggio prosegue verso la chat unica / Make come se nulla fosse.
        if (env.TIMBRATURE !== "off" && msg.type === "text" && timbraturaParola(msg.text && msg.text.body)) {
          let presa = false;
          try { presa = await timbraturaGestisci(msg, value, env, supabaseUrl, graph); } catch (e) { presa = false; }
          if (presa) continue;
        }
        if (cu.numeri.length && cu.numeri.indexOf(String(msg.from || "")) !== -1) {
          let presa = false;
          try { presa = await chatUnicaGestisci(msg, value, env, supabaseUrl, graph, cu, bundle, inoltraAMake); } catch (e) { presa = false; }
          if (presa) continue; // gestito dalla chat unica (prova o produzione): il pacchetto originale NON va a Make
        }
        await inoltraAMake(bundle);
      }
    }
  }
}

async function captureMedia(mediaId, tipo, msg, env, supabaseUrl, graph) {
  const token = env.WHATSAPP_TOKEN;
  const svc = env.SUPABASE_SERVICE_KEY;
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 25000);
  try {
    // 1) risolvi l'indirizzo del media presso Meta
    const metaResp = await fetch(graph + "/" + mediaId, {
      headers: { Authorization: "Bearer " + token }, signal: ctrl.signal
    });
    if (!metaResp.ok) throw new Error("resolve " + metaResp.status);
    const meta = await metaResp.json();
    const mime = meta.mime_type || (msg[tipo] && msg[tipo].mime_type) || "application/octet-stream";
    // 2) scarica i byte (il Bearer serve anche sull'URL del media)
    const binResp = await fetch(meta.url, {
      headers: { Authorization: "Bearer " + token }, signal: ctrl.signal
    });
    if (!binResp.ok) throw new Error("download " + binResp.status);
    const bytes = new Uint8Array(await binResp.arrayBuffer());
    // 3) percorso stabile nel bucket wa-media
    const now = new Date();
    const yyyy = now.getUTCFullYear();
    const mm = String(now.getUTCMonth() + 1).padStart(2, "0");
    const dd = String(now.getUTCDate()).padStart(2, "0");
    const path = tipo + "/" + yyyy + "/" + mm + "/" + dd + "/" + mediaId + extFromMime(mime);
    // 4) upload su Supabase Storage (upsert)
    const upResp = await fetch(supabaseUrl + "/storage/v1/object/wa-media/" + path, {
      method: "POST",
      headers: { Authorization: "Bearer " + svc, apikey: svc, "Content-Type": mime, "x-upsert": "true" },
      body: bytes, signal: ctrl.signal
    });
    if (!upResp.ok) throw new Error("upload " + upResp.status + " " + (await upResp.text()).slice(0, 120));
    // 5) URL firmato (7 giorni) per il consumo da Make senza header di auth
    const signResp = await fetch(supabaseUrl + "/storage/v1/object/sign/wa-media/" + path, {
      method: "POST",
      headers: { Authorization: "Bearer " + svc, apikey: svc, "Content-Type": "application/json" },
      body: JSON.stringify({ expiresIn: 604800 }), signal: ctrl.signal
    });
    if (!signResp.ok) throw new Error("sign " + signResp.status);
    const signJson = await signResp.json();
    const signedUrl = supabaseUrl + "/storage/v1" + signJson.signedURL;
    const scade = new Date(Date.now() + 604800 * 1000).toISOString();
    // 6) registro (idempotente sul WAMID)
    await logMedia(env, supabaseUrl, {
      message_id: msg.id, telefono: msg.from, tipo, mime, storage_path: path,
      signed_url: signedUrl, signed_url_scade: scade, dimensione_bytes: bytes.length,
      esito: "ok", errore: null
    });
    return { storage_path: path, signed_url: signedUrl, signed_url_scade: scade, mime, bytes: bytes.length, esito: "ok" };
  } finally {
    clearTimeout(timer);
  }
}

